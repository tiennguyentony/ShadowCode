/**
 * QR_Sheet generator (race spec, Requirement 8; design D10, D11).
 *
 * Builds print/qr-codes.html (one A4 page, one QR code per product) and
 * print/products.js (the product list for print/labels.html) from the
 * Product_Catalog in web/src/config.ts. Run by web/scripts/gen-print-pages.mjs.
 * The QR module matrix comes from the `qrcode` package (MIT); the SVG is drawn
 * here so its size is set in millimetres.
 */
import QRCode from 'qrcode'
import type { Product } from '../config'

/** Width of the QR_Symbol (modules only, without the Quiet_Zone) on paper. At least 30 mm (8.4). */
export const QR_SYMBOL_MM = 42
/** Quiet_Zone on each side, in modules (8.5). */
export const QUIET_ZONE_MODULES = 4
export const QR_ERROR_CORRECTION = 'M'

const GENERATED_NOTE =
  'Generated by web/scripts/gen-print-pages.mjs from web/src/config.ts. Do not edit; run `npm run print:gen` in /web.'

export interface QrMatrix {
  readonly text: string
  /** Modules per side. */
  readonly size: number
  /** dark[row][col] */
  readonly dark: readonly (readonly boolean[])[]
}

export function qrMatrix(text: string): QrMatrix {
  const { modules } = QRCode.create(text, { errorCorrectionLevel: QR_ERROR_CORRECTION })
  const dark = Array.from({ length: modules.size }, (_, row) =>
    Array.from({ length: modules.size }, (_, col) => modules.get(row, col) === 1),
  )
  return { text, size: modules.size, dark }
}

const mm = (value: number) => `${Number(value.toFixed(4))}mm`

function escapeHtml(text: string): string {
  return text.replace(/[&<>"']/g, (c) => `&#${c.charCodeAt(0)};`)
}

/** One QR code as SVG: viewBox in modules (Quiet_Zone included), size in mm. */
export function qrSvg(matrix: QrMatrix): string {
  const total = matrix.size + 2 * QUIET_ZONE_MODULES
  const moduleMm = QR_SYMBOL_MM / matrix.size
  const runs: string[] = []
  matrix.dark.forEach((row, r) => {
    let c = 0
    while (c < row.length) {
      if (!row[c]) {
        c++
        continue
      }
      const from = c
      while (c < row.length && row[c]) c++
      runs.push(`M${from + QUIET_ZONE_MODULES} ${r + QUIET_ZONE_MODULES}h${c - from}v1h-${c - from}z`)
    }
  })
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${mm(total * moduleMm)}" height="${mm(total * moduleMm)}"`,
    ` viewBox="0 0 ${total} ${total}" shape-rendering="crispEdges"`,
    ` data-text="${escapeHtml(matrix.text)}" data-modules="${matrix.size}" data-module-mm="${Number(moduleMm.toFixed(6))}"`,
    ` data-quiet-modules="${QUIET_ZONE_MODULES}">`,
    `<rect width="${total}" height="${total}" fill="#fff"/>`,
    `<path fill="#000" d="${runs.join('')}"/>`,
    `</svg>`,
  ].join('')
}

export function qrSheetHtml(products: readonly Product[]): string {
  const cells = products
    .map((p) => {
      const svg = qrSvg(qrMatrix(String(p.id)))
      return [
        `      <div class="cell" data-product-id="${p.id}">`,
        `        ${svg}`,
        `        <div class="name">${escapeHtml(p.name)}</div>`,
        `        <div class="id">ID ${p.id}</div>`,
        `      </div>`,
      ].join('\n')
    })
    .join('\n')
  return `<!doctype html>
<!-- ${GENERATED_NOTE} -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <title>Tilemark race: QR codes</title>
    <style>
      @page { size: A4; margin: 0; }
      html, body { margin: 0; padding: 0; }
      body { font: 11pt/1.3 system-ui, sans-serif; color: #000; }
      .sheet { position: relative; width: 210mm; height: 297mm; overflow: hidden; background: #fff; }
      .cells { position: absolute; left: 65mm; top: 21mm; width: 80mm; }
      .cell { box-sizing: border-box; width: 80mm; height: 85mm; border: 0.3mm dashed #000;
              display: flex; flex-direction: column; align-items: center; justify-content: center; }
      .cell + .cell { border-top: none; }
      .cell svg { display: block; }
      .name { margin-top: 1mm; font-weight: 600; }
      .id { font-family: ui-monospace, Consolas, monospace; }
      .note { position: absolute; left: 0; right: 0; top: 280mm; margin: 0; text-align: center; font-size: 9pt; }
      @media screen {
        body { background: #ccc; padding: 10mm 0; }
        .sheet { margin: 0 auto; box-shadow: 0 1mm 4mm rgba(0, 0, 0, 0.3); }
      }
    </style>
  </head>
  <body>
    <div class="sheet">
      <div class="cells">
${cells}
      </div>
      <p class="note">Print at 100% (actual size). Cut along the dashed lines. One code per box, on one side only.</p>
    </div>
  </body>
</html>
`
}

/** print/products.js: the product list for the Label_Sheets (classic script, works from file://). */
export function productsScript(products: readonly Product[]): string {
  const items = products.map((p) => `  ${JSON.stringify({ id: p.id, name: p.name })},`).join('\n')
  return `// ${GENERATED_NOTE}\nglobalThis.TILEMARK_PRODUCTS = [\n${items}\n];\n`
}
